// Generates src/services/analyticsTimeZones.ts: a time zone → country table used
// to report the user's country to Google Analytics without any IP lookup.
//
// Run with Node 18+ on macOS or Linux:  node scripts/generate-timezone-countries.mjs
//
// Sources:
//  - zone.tab from the system time zone database: one country per zone.
//  - Intl.supportedValuesOf('timeZone'): the zone names browsers actually report.
//    These include older names (Asia/Calcutta, Europe/Kiev) that zone.tab lists
//    under their new names; they are matched by identical zone data, and only
//    when that points to a single country.

import crypto from 'crypto'
import fs from 'fs'
import path from 'path'

const ZONEINFO = '/usr/share/zoneinfo'
const OUT = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'src', 'services', 'analyticsTimeZones.ts')

const hashOf = (zone) => {
  try {
    return crypto.createHash('sha1').update(fs.readFileSync(path.join(ZONEINFO, zone))).digest('hex')
  } catch {
    return undefined
  }
}

const countryByZone = new Map()
for (const line of fs.readFileSync(path.join(ZONEINFO, 'zone.tab'), 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue
  const [country, , zone] = line.split('\t')
  countryByZone.set(zone, country)
}

const countriesByHash = new Map()
for (const [zone, country] of countryByZone) {
  const hash = hashOf(zone)
  if (!hash) continue
  if (!countriesByHash.has(hash)) countriesByHash.set(hash, new Set())
  countriesByHash.get(hash).add(country)
}

// Older names browsers still report whose zone data is shared with other
// countries, so they cannot be matched automatically.
const MANUAL = {
  'Africa/Asmera': 'ER',
  'America/Coral_Harbour': 'CA',
  'Asia/Rangoon': 'MM',
  'Pacific/Ponape': 'FM',
  'Pacific/Truk': 'FM',
}

const result = new Map(countryByZone)
let aliases = 0
for (const [zone, country] of Object.entries(MANUAL)) {
  if (!result.has(zone)) {
    result.set(zone, country)
    aliases++
  }
}
for (const zone of Intl.supportedValuesOf('timeZone')) {
  if (result.has(zone) || zone.startsWith('Etc/') || !zone.includes('/')) continue
  const countries = countriesByHash.get(hashOf(zone))
  if (countries?.size === 1) {
    result.set(zone, [...countries][0])
    aliases++
  }
}

// Compact form: "FI:Europe/Helsinki|SE:Europe/Stockholm,Arctic/Longyearbyen|..."
const zonesByCountry = new Map()
for (const [zone, country] of [...result].sort((a, b) => a[0].localeCompare(b[0]))) {
  if (!zonesByCountry.has(country)) zonesByCountry.set(country, [])
  zonesByCountry.get(country).push(zone)
}
const packed = [...zonesByCountry]
  .sort((a, b) => a[0].localeCompare(b[0]))
  .map(([country, zones]) => `${country}:${zones.join(',')}`)
  .join('|')

const version = fs.readFileSync(path.join(ZONEINFO, '+VERSION'), 'utf8').trim()
// Wrap into source lines of whole entries ("|" stays at the end of each line).
const chunks = []
for (const entry of packed.split('|')) {
  const last = chunks.length - 1
  if (last >= 0 && chunks[last].length + entry.length < 110) chunks[last] += `|${entry}`
  else chunks.push(entry)
}
for (let i = 0; i < chunks.length - 1; i++) chunks[i] += '|'
if (chunks.join('') !== packed) throw new Error('wrapping changed the table')

fs.writeFileSync(
  OUT,
  `// Generated by scripts/generate-timezone-countries.mjs (tz database ${version}). Do not edit.
//
// Time zone → ISO 3166-1 country code, packed as "CC:Zone,Zone|CC:Zone".
// Zones shared by several countries (e.g. Etc/UTC) are not listed.

const PACKED =
${chunks.map((c) => `  '${c}'`).join(' +\n')}

let table: Map<string, string> | undefined

/** ISO 3166-1 alpha-2 country for an IANA time zone, or undefined if unknown. */
export function countryForTimeZone(timeZone: string): string | undefined {
  if (!table) {
    table = new Map()
    for (const entry of PACKED.split('|')) {
      const [country, zones] = entry.split(':')
      for (const zone of zones.split(',')) table.set(zone, country)
    }
  }
  return table.get(timeZone)
}
`,
)

console.log(`Wrote ${OUT}: ${result.size} zones (${aliases} older names), ${zonesByCountry.size} countries, ${packed.length} chars`)
